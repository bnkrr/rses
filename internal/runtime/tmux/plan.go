package tmux

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"path/filepath"
	"sort"
	"strings"
	"time"
	"unicode"

	"github.com/bnkrr/rses/internal/session"
)

const RemoteStateRoot = "$HOME/.local/state/rses"

type RuntimeRecord struct {
	Name       string     `json:"name"`
	ProjectDir string     `json:"project_dir"`
	Kind       string     `json:"kind"`
	Host       string     `json:"host,omitempty"`
	Group      string     `json:"group,omitempty"`
	Tags       []string   `json:"tags,omitempty"`
	Summary    string     `json:"summary,omitempty"`
	Scope      string     `json:"scope"`
	Window     string     `json:"window"`
	StateDir   string     `json:"state_dir"`
	RunPath    string     `json:"run_path"`
	LogPath    string     `json:"log_path"`
	StartedAt  *time.Time `json:"started_at,omitempty"`
}

type Plan struct {
	Spec          session.Spec
	ProjectDir    string
	Scope         string
	Window        string
	Target        string
	StateDir      string
	RunPath       string
	LogPath       string
	RecordPath    string
	RunScript     string
	RecordJSON    string
	InstallScript string
	StatusScript  string
	StartScript   string
	StopScript    string
	LogScript     string
	AttachCommand []string
}

func NewPlan(spec session.Spec, projectDir, stateRoot string, logLines int) (Plan, error) {
	if logLines <= 0 {
		logLines = 200
	}
	if stateRoot == "" {
		stateRoot = RemoteStateRoot
	}
	scope := ScopeForProject(projectDir)
	window := SafeName(spec.Name)
	stateDir := StateDir(spec, stateRoot, scope, window)
	runPath := join(stateDir, "run.sh")
	logPath := join(stateDir, "output.log")
	recordPath := join(stateDir, "record.json")
	runScript := RunScript(spec)
	record := RuntimeRecord{
		Name:       spec.Name,
		ProjectDir: cleanProjectDir(projectDir),
		Kind:       spec.Kind(),
		Host:       spec.Host,
		Group:      spec.Group,
		Tags:       spec.Tags,
		Summary:    spec.Summary,
		Scope:      scope,
		Window:     window,
		StateDir:   stateDir,
		RunPath:    runPath,
		LogPath:    logPath,
	}
	recordJSON, err := RecordJSON(record)
	if err != nil {
		return Plan{}, err
	}
	plan := Plan{
		Spec:          spec,
		ProjectDir:    cleanProjectDir(projectDir),
		Scope:         scope,
		Window:        window,
		Target:        scope + ":" + window,
		StateDir:      stateDir,
		RunPath:       runPath,
		LogPath:       logPath,
		RecordPath:    recordPath,
		RunScript:     runScript,
		RecordJSON:    recordJSON,
		StatusScript:  StatusScript(scope, window),
		StopScript:    StopScript(scope, window),
		LogScript:     LogScript(logPath, scope, window, logLines),
		AttachCommand: attachCommand(spec, scope),
	}
	plan.InstallScript = InstallScript(plan, runScript, recordJSON)
	plan.StartScript = StartScript(plan)
	return plan, nil
}

func ScopeForProject(projectDir string) string {
	projectDir = cleanProjectDir(projectDir)
	sum := sha256.Sum256([]byte(projectDir))
	return fmt.Sprintf("rses-%x", sum[:6])
}

func SafeName(name string) string {
	name = strings.TrimSpace(name)
	var b strings.Builder
	for _, r := range name {
		switch {
		case r == '-' || r == '_' || r == '.':
			b.WriteRune(r)
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	out := strings.Trim(b.String(), "._-")
	if out == "" || out == "." || out == ".." {
		return "session"
	}
	return out
}

func StateDir(spec session.Spec, stateRoot, scope, window string) string {
	if spec.StateDir != "" {
		return spec.StateDir
	}
	return join(join(join(stateRoot, "scopes"), scope), "sessions/"+window)
}

func RunScript(spec session.Spec) string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by rses from structured command.argv; inspectable for debugging.\n")
	b.WriteString("set -eu\n")
	if spec.Command.Cwd != "" {
		b.WriteString("cd ")
		b.WriteString(ShellQuote(spec.Command.Cwd))
		b.WriteString("\n")
	}
	if len(spec.Command.Env) > 0 {
		keys := make([]string, 0, len(spec.Command.Env))
		for key := range spec.Command.Env {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			b.WriteString("export ")
			b.WriteString(key)
			b.WriteString("=")
			b.WriteString(ShellQuote(spec.Command.Env[key]))
			b.WriteString("\n")
		}
	}
	b.WriteString("exec")
	for _, arg := range spec.Command.Argv {
		b.WriteByte(' ')
		b.WriteString(ShellQuote(arg))
	}
	b.WriteByte('\n')
	return b.String()
}

func RecordJSON(record RuntimeRecord) (string, error) {
	data, err := json.MarshalIndent(record, "", "  ")
	if err != nil {
		return "", err
	}
	return string(data) + "\n", nil
}

func attachCommand(spec session.Spec, scope string) []string {
	if spec.IsRemote() {
		return []string{"ssh", "-t", spec.Host, "tmux", "attach", "-t", scope}
	}
	return []string{"tmux", "attach", "-t", scope}
}

func cleanProjectDir(projectDir string) string {
	if projectDir == "" {
		return ""
	}
	abs, err := filepath.Abs(projectDir)
	if err == nil {
		return filepath.Clean(abs)
	}
	return filepath.Clean(projectDir)
}

func join(dir, name string) string {
	return strings.TrimRight(dir, "/") + "/" + strings.TrimLeft(name, "/")
}
